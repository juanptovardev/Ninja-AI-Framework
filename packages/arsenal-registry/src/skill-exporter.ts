import type { SkillDefinition } from './schema.js';

/**
 * ExportedSkill is the structural shape used by `exportSkillsForInjection`
 * to return skill content that is compatible with NinjaSkill. We define it
 * locally here to avoid creating a circular dependency between
 * @ninja/arsenal-registry and @ninja/installer.
 */
export interface ExportedSkill {
  id: string;
  filename: string;
  content: string;
  subfolder?: string;
}

export function exportSkillsForInjection(skills: Map<string, SkillDefinition>): ExportedSkill[] {
  const result: ExportedSkill[] = [];

  for (const skill of skills.values()) {
    const toolsLine = skill.tools.length > 0 ? skill.tools.join(', ') : '(none)';

    const content = [
      `# ${skill.name}`,
      '',
      skill.description,
      '',
      `## Tools: ${toolsLine}`,
      '',
      `## Agent Role: ${skill.agentRole}`,
      '',
      '---',
      '',
      'Arsenal-managed skill. Auto-generated by Ninja AI Framework.',
      '',
    ].join('\n');

    result.push({
      id: skill.id,
      filename: `${skill.id}.md`,
      content,
    });
  }

  return result;
}
